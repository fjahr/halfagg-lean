#!/usr/bin/env python3
"""Generate Halfagg/OrderCert.lean: a certificate that `(n - 1)⋅G = -G` on secp256k1.

Usage: python3 scripts/gen_order_cert.py > Halfagg/OrderCert.lean

The certificate is the double-and-add chain for the scalar `n - 1`, most
significant bit first, starting from `G`. Every step lists the slope of the
line and the coordinates of the result, so that checking a step needs only
multiplications and additions modulo `p`. `Halfagg/OrderG.lean` checks the
chain in Lean's kernel and derives `n⋅G = 0` from it.

Nothing here has to be trusted: a wrong certificate fails the check.
"""

P = 2**256 - 2**32 - 977
N = 0xFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFEBAAEDCE6AF48A03BBFD25E8CD0364141
GX = 0x79BE667EF9DCBBAC55A06295CE870B07029BFCDB2DCE28D959F2815B16F81798
GY = 0x483ADA7726A3C4655DA4FBFC0E1108A8FD17B448A68554199C47D08FFB10D4B8


def double(x, y):
    l = 3 * x * x * pow(2 * y, -1, P) % P
    x3 = (l * l - 2 * x) % P
    return l, x3, (l * (x - x3) - y) % P


def add_g(x, y):
    l = (y - GY) * pow(x - GX, -1, P) % P
    x3 = (l * l - x - GX) % P
    return l, x3, (l * (x - x3) - y) % P


def main():
    steps = []
    k, x, y = 1, GX, GY
    for bit in bin(N - 1)[3:]:
        l, x, y = double(x, y)
        k *= 2
        steps.append((False, l, x, y))
        if bit == "1":
            l, x, y = add_g(x, y)
            k += 1
            steps.append((True, l, x, y))
    assert (k, x, y) == (N - 1, GX, P - GY)
    out = ['''/-!
# A certificate for the order of the generator of secp256k1

The double-and-add chain for `(n - 1)⋅G`, most significant bit first, starting
from `G`. A step is `(addG, ℓ, x, y)`: with `addG = false` the point is
doubled, with `addG = true` the generator is added, `ℓ` is the slope of the
line and `(x, y)` the result. `Halfagg.OrderG` checks every step.

Generated by `scripts/gen_order_cert.py`.
-/

namespace Halfagg.OrderG

/-- The chain for `(n - 1)⋅G`. -/
def cert : List (Bool × Nat × Nat × Nat) := [''']
    for i, (a, l, sx, sy) in enumerate(steps):
        sep = "," if i + 1 < len(steps) else "]"
        out.append(f"  ({'true' if a else 'false'}, 0x{l:064x}, 0x{sx:064x}, 0x{sy:064x}){sep}")
    out.append("")
    out.append("end Halfagg.OrderG")
    print("\n".join(out))


if __name__ == "__main__":
    main()
