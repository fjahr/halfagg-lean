#!/usr/bin/env python3
"""Generate Halfagg/VectorData.lean from the BIP 458 test vector CSV files.

Usage: python3 scripts/gen_vectors.py <path to bip-0458/vectors> > Halfagg/VectorData.lean
"""

import csv
import json
import sys
from pathlib import Path


def lean_str(s):
    return json.dumps(s, ensure_ascii=True)


def lean_list(hex_str):
    if not hex_str:
        return "[]"
    return "[" + ", ".join(lean_str(h) for h in hex_str.split(";")) + "]"


def lean_opt(s):
    return "none" if s is None else f"some {lean_str(s)}"


def rows(path):
    with open(path, newline="", encoding="utf-8") as f:
        reader = csv.reader(f)
        next(reader)
        return list(reader)


def main():
    d = Path(sys.argv[1])
    out = []
    out.append("import Halfagg.VectorTypes")
    out.append("")
    out.append("/-! Generated by `scripts/gen_vectors.py` from `bip-0458/vectors/*.csv`. Do not edit. -/")
    out.append("")
    out.append("namespace Halfagg.Vectors")
    out.append("")

    out.append("def aggregateVectors : List AggregateVector := [")
    items = []
    for index, pks, msgs, sigs, result, aggsig, comment in rows(d / "test_vectors_aggregate.csv"):
        expected = aggsig if result == "TRUE" else None
        items.append(f"  ⟨{index}, {lean_list(pks)}, {lean_list(msgs)}, {lean_list(sigs)},\n"
                     f"    {lean_opt(expected)}, {lean_str(comment)}⟩")
    out.append(",\n".join(items) + "]")
    out.append("")

    out.append("def incAggregateVectors : List IncAggregateVector := [")
    items = []
    for (index, aggsig, pm_pks, pm_msgs, pks, msgs, sigs, result, expected_aggsig,
         comment) in rows(d / "test_vectors_incaggregate.csv"):
        expected = expected_aggsig if result == "TRUE" else None
        items.append(f"  ⟨{index}, {lean_str(aggsig)}, {lean_list(pm_pks)}, {lean_list(pm_msgs)},\n"
                     f"    {lean_list(pks)}, {lean_list(msgs)}, {lean_list(sigs)},\n"
                     f"    {lean_opt(expected)}, {lean_str(comment)}⟩")
    out.append(",\n".join(items) + "]")
    out.append("")

    out.append("def verifyVectors : List VerifyVector := [")
    items = []
    for index, aggsig, pks, msgs, result, comment in rows(d / "test_vectors_verify.csv"):
        assert result in ("TRUE", "FALSE")
        items.append(f"  ⟨{index}, {lean_str(aggsig)}, {lean_list(pks)}, {lean_list(msgs)},\n"
                     f"    {'true' if result == 'TRUE' else 'false'}, {lean_str(comment)}⟩")
    out.append(",\n".join(items) + "]")
    out.append("")
    out.append("end Halfagg.Vectors")
    print("\n".join(out))


if __name__ == "__main__":
    main()
